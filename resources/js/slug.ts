/** A suggested workspace address from its name; the server checks length, reserved words and taken slugs. */
export const slugify = (name: string) =>
    name
        .toLowerCase()
        .normalize('NFKD')
        .replace(/[̀-ͯ]/g, '')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, 40)
        .replace(/-+$/, '');
